-- 검색 '추천 순'의 정렬 키를 컬럼으로 둔다 (DEC-023).
--
-- 인기(좋아요·저장·조회)와 신선도를 합친 값이며 배치가 주기적으로 갱신한다.
-- 조회할 때마다 계산하지 않는 이유는 두 가지다.
--   (1) 함수 결과로 정렬하면 인덱스를 태울 수 없다
--   (2) 요청 사이에 값이 바뀌면 커서 경계가 흔들려 스크롤에서 중복·누락이 난다 (DEC-022)
--
-- 인덱스는 지금 만들지 않는다 — 검색 쿼리 형태가 확정되지 않았고,
-- 쓰지 않는 인덱스는 쓰기 비용만 남긴다(IDX-003 과 같은 기준).
ALTER TABLE `post`
  ADD COLUMN `rank_score` DECIMAL(6,4) NOT NULL DEFAULT 0
    COMMENT '검색 추천 순 정렬 키. 배치가 인기·신선도로 계산한다 (DEC-023)' AFTER `view_count`;
